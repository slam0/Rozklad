NSInteger RZLangChoice(void)
{
    NSInteger i = [[NSUserDefaults standardUserDefaults] integerForKey:kLangKey];
    return (i >= 0 && i <= 3) ? i : 0;
}

NSInteger RZLangCurrent(void)
{
    NSInteger c = RZLangChoice();
    if (c >= 1) return c - 1;
    /* automatycznie: pierwszy język z ustawień telefonu, a gdy go nie znamy, angielski */
    NSArray *prefs = [NSLocale preferredLanguages];
    NSString *first = [prefs count] ? [[prefs objectAtIndex:0] lowercaseString] : @"en";
    if ([first hasPrefix:@"pl"]) return 0;
    if ([first hasPrefix:@"ru"]) return 2;
    return 1;
}

NSString *RZLangCode(void)
{
    switch (RZLangCurrent()) {
        case 0:  return @"pl";
        case 2:  return @"ru";
        default: return @"en";
    }
}

void RZLangApply(void)
{
    rz_set_lang((int)RZLangCurrent());
}

void RZLangSet(NSInteger choice)
{
    if (choice < 0 || choice > 3) return;
    NSUserDefaults *d = [NSUserDefaults standardUserDefaults];
    [d setInteger:choice forKey:kLangKey];
    [d synchronize];
    RZLangApply();
    [[NSNotificationCenter defaultCenter] postNotificationName:RZLanguageDidChangeNotification object:nil];
}

NSString *RZL(NSString *polish)
{
    NSInteger lang = RZLangCurrent();
    if (lang == 0 || !polish) return polish;
    static NSDictionary *index = nil;
    if (!index) {
        NSMutableDictionary *d = [NSMutableDictionary dictionary];
        for (NSUInteger i = 0; i < sizeof(kTable) / sizeof(kTable[0]); i++) {
            [d setObject:[NSNumber numberWithUnsignedInteger:i] forKey:kTable[i][0]];
        }
        index = d;
    }
    NSNumber *n = [index objectForKey:polish];
    if (!n) return polish;
    return kTable[[n unsignedIntegerValue]][lang];
}
